#!/usr/bin/env node
/**
 * Build the tiny EMBEDDED emergency fallback for the World Cup Draft.
 *
 * The full bundled JSON (`public/data/world-cup-draft-database.json`) is ~16 MB
 * and lives as a separate asset; on a flaky mobile network — or behind a stale
 * Hosting rewrite/HTTP cache that returns the SPA HTML shell instead of the
 * JSON — that fetch can fail even though Firestore is also denied/unavailable.
 * When BOTH primary sources fail the setup screen used to dead-end on a red
 * "No se pudo cargar la base del draft" error with EMPEZAR DRAFT disabled.
 *
 * This script extracts a curated handful of iconic national squads (real data,
 * verbatim from the bundled JSON) and emits a small JS module that ships INSIDE
 * the app bundle. The loader uses it only as a last resort so a player can
 * always start a draft, clearly labelled `source: 'emergency'`.
 *
 * Run after the bundled JSON changes:
 *   node scripts/world-cup-draft/build-emergency-fallback.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const DATA_PATH = join(ROOT, 'public', 'data', 'world-cup-draft-database.json');
const OUT_PATH = join(ROOT, 'src', 'components', 'WorldCupDraft', 'worldCupDraftEmergencyData.js');

// Iconic, era-spread squads with strong country/style chemistry overlaps
// (multiple BRA/ARG/GER editions) so even the emergency deck builds real links.
const SELECTED = [
  { year: 1970, code: 'BRA' },
  { year: 1974, code: 'NED' },
  { year: 1982, code: 'ITA' },
  { year: 1986, code: 'ARG' },
  { year: 1990, code: 'FRG' },
  { year: 1998, code: 'FRA' },
  { year: 2002, code: 'BRA' },
  { year: 2010, code: 'ESP' },
  { year: 2014, code: 'GER' },
  { year: 2022, code: 'ARG' },
];

// Every slot label the formations in WorldCupDraft.jsx can ask for, mapped to
// the player position tokens that satisfy it (kept in sync with
// SLOT_COMPATIBLE_POSITIONS). The emergency deck must cover all of them or some
// positions would be undraftable.
const SLOT_COMPATIBLE_POSITIONS = {
  GK: ['GK'], LB: ['LB'], RB: ['RB'], CB: ['CB'], LM: ['LM'], RM: ['RM'],
  LW: ['LW'], RW: ['RW'], CM: ['CM'], DM: ['DM', 'CDM'], AM: ['AM', 'CAM'], ST: ['ST', 'CF'],
};
const POSITION_ALIASES = { MC: 'CM', MI: 'LM', MD: 'RM', MCD: 'CDM', MCO: 'CAM', DC: 'ST' };
const norm = (p) => {
  const t = String(p || '').trim().toUpperCase();
  return POSITION_ALIASES[t] || t;
};

const raw = JSON.parse(readFileSync(DATA_PATH, 'utf-8'));
const byYear = new Map(raw.editions.map((e) => [Number(e.year), e]));

const editionsOut = [];
for (const { year, code } of SELECTED) {
  const edition = byYear.get(year);
  if (!edition) throw new Error(`emergency-fallback: edition ${year} missing from bundled JSON`);
  const team = (edition.teams || []).find((t) => String(t.code).toUpperCase() === code);
  if (!team) throw new Error(`emergency-fallback: ${code} ${year} missing from bundled JSON`);
  editionsOut.push({ year: Number(edition.year), source: edition.source, teams: [team] });
}

// Coverage check: the emergency deck must cover every slot label that the FULL
// bundled database can cover. Some labels (e.g. LM/RM) have no compatible token
// anywhere in the source data, so they are unfillable with the full DB too —
// we only require parity, not absolute coverage.
const positionsOf = (editions) => {
  const set = new Set();
  for (const e of editions) {
    for (const t of e.teams) {
      for (const p of t.players || []) {
        [p.position, ...(Array.isArray(p.positions) ? p.positions : [])].map(norm).filter(Boolean).forEach((x) => set.add(x));
      }
    }
  }
  return set;
};
const fullPositions = positionsOf(raw.editions);
const emergencyPositions = positionsOf(editionsOut);
const coverableSlots = Object.entries(SLOT_COMPATIBLE_POSITIONS)
  .filter(([, toks]) => toks.some((tok) => fullPositions.has(tok)))
  .map(([slot]) => slot);
const uncovered = coverableSlots.filter(
  (slot) => !SLOT_COMPATIBLE_POSITIONS[slot].some((tok) => emergencyPositions.has(tok)),
);
if (uncovered.length) {
  throw new Error(`emergency-fallback: no compatible players for slot(s): ${uncovered.join(', ')}. Add more squads to SELECTED.`);
}

const playerCount = editionsOut.reduce((s, e) => s + e.teams.reduce((ss, t) => ss + (t.players?.length || 0), 0), 0);

const banner = `// AUTO-GENERATED by scripts/world-cup-draft/build-emergency-fallback.mjs — do not edit by hand.
// A tiny, real subset of the World Cup Draft database embedded in the app bundle
// so the setup screen can ALWAYS start a draft, even when both Firestore and the
// full bundled JSON fetch fail. Regenerate after the bundled JSON changes.
// Squads: ${SELECTED.map((s) => `${s.code} ${s.year}`).join(', ')} (${playerCount} players).
`;

const body = `export const WORLD_CUP_DRAFT_EMERGENCY_DATABASE = ${JSON.stringify({ editions: editionsOut })};\n`;

writeFileSync(OUT_PATH, `${banner}\n${body}`);
const bytes = Buffer.byteLength(`${banner}\n${body}`, 'utf-8');
console.log(`emergency-fallback: wrote ${editionsOut.length} editions, ${playerCount} players, ${(bytes / 1024).toFixed(1)} KiB -> ${OUT_PATH}`);
